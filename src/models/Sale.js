const mongoose = require('mongoose');

const itemSchema = new mongoose.Schema(
  {
    product: { type: mongoose.Schema.Types.ObjectId, ref: 'Product', required: true },
    sku: String,
    name: String,
    category: String,
    qty: { type: Number, required: true, min: 1 },
    unitPrice: { type: Number, required: true },
    costPrice: { type: Number, default: 0 },
    taxPercent: { type: Number, default: 0 },
    discount: { type: Number, default: 0 },
    offerTitle: String,
    taxAmount: { type: Number, default: 0 },
    lineTotal: { type: Number, required: true },
    codes: { type: [String], default: [] }, // unit QR codes sold on this line
  },
  { _id: false }
);

const saleSchema = new mongoose.Schema(
  {
    invoiceNo: { type: String, required: true, unique: true },
    // Generated by the client app once per cart. A unique index makes retries and double taps safe.
    clientRequestId: { type: String, required: true, unique: true },
    source: { type: String, enum: ['POS', 'SELF'], required: true },
    customer: { type: mongoose.Schema.Types.ObjectId, ref: 'User', index: true },
    customerName: { type: String, trim: true, maxlength: 100 },
    createdBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, index: true },
    items: { type: [itemSchema], validate: (v) => v.length > 0 },
    subtotal: Number,
    discountTotal: Number,
    taxTotal: Number,
    grandTotal: { type: Number, required: true },
    paymentMode: { type: String, enum: ['cash', 'card', 'upi'] },
    status: {
      type: String,
      enum: ['PENDING_PAYMENT', 'PAID', 'CANCELLED', 'REFUNDED'],
      required: true,
      index: true,
    },
    paidAt: Date,
    paidBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    reservedUntil: { type: Date, index: true },
    cancelReason: String,
    refundedAt: Date,
    refundedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    refundReason: String,
  },
  { timestamps: true }
);

saleSchema.index({ createdAt: -1 });

module.exports = mongoose.model('Sale', saleSchema);
